/**
 * ⚙️ Конфигурация поведения декоратора кэширования withCache
 */
export interface CacheOptions {
  /**
   * Время жизни кэша в миллисекундах (Time-To-Live).
   * После истечения этого интервала с момента записи, кэш считается
   * невалидным, и следующий вызов спровоцирует свежий сетевой запрос.
   * @default 300000 (5 минут)
   */
  ttl?: number
}

/**
 * 📦 Структура единичной записи, сохраняемой во внутреннем кэше Map
 */
export interface CacheEntry<T> {
  /**
   * Физические данные, возвращенные оригинальным асинхронным фетчером.
   * Дженерик <T> позволяет кэшировать структуры любой сложности (массивы, объекты, строки).
   */
  data: T

  /**
   * Метка времени (в миллисекундах, Unix Timestamp), зафиксированная
   * строго в момент успешного завершения промиса фетчера.
   * Используется для последующей валидации по TTL.
   */
  timestamp: number
}
